// The chapter's voice recordings: what needs recording, and turning takes into
// game audio.
//
// 1. Collects every spoken line by playing each scene's story through many
//    random routes (so lines that change with the story, "$800" or "the
//    sedan", are caught in every form a player can meet): what each character
//    says, the line a choice is asked with, everything Rookie can say back
//    (each dialogue option, as the game echoes it: ChoiceSystem.spokenLine),
//    and the asides when he looks at something. Unspoken thoughts aren't voiced.
//    Writes one script sheet per character in art-source/voices/scripts/.
// 2. Takes: art-source/voices/takes/<speaker>/<key>.<webm|wav|m4a|mp3|ogg>,
//    generated by Kokoro (2b), or real recordings dropped in
//    art-source/voices/inbox/ named <speaker>__<key>.<ext> (the names on the
//    script sheets) and filed from there. Takes are the masters.
// 3. Each take is trimmed of silence at both ends, levelled to one loudness
//    and saved as the game's two formats (Opus/WebM, MP3) in
//    public/assets/audio/voice/<speaker>/; src/story/voices.json lists them.
//    A line whose words change gets a new key, so it plays silent until it's
//    recorded again.
//
//   npm run voices                         collect, file, convert, report what's left to record
//   npm run voices -- --audition           one line per character in its Kokoro voice (art-source/voices/auditions/)
//   npm run voices -- --generate           Kokoro voices every line that has no take yet
//   npm run voices -- --generate --only=victor --limit=5
//   npm run voices -- --redo=victor --generate   re-voice a character after changing their voice (generated takes only)
//   npm run voices -- --prune              also move takes no current line uses to art-source/voices/unused/
//
// Voices come from Kokoro (free, runs on this machine, nothing is sent
// anywhere), installed apart from the game in tools/kokoro. A real recording
// dropped in the inbox replaces a line's generated take.

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readFileSync, readdirSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs'
import { dirname, extname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { compileInk } from './lib/ink-compile.mjs'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const imp = (p) => import(pathToFileURL(resolve(ROOT, p)).href)
const { StoryRuntime } = await imp('src/game/narrative/StoryRuntime.ts')
const { DEFAULT_VARS } = await imp('src/game/narrative/NarrativeState.ts')
const { spokenLine } = await imp('src/game/narrative/ChoiceSystem.ts')
const { voiceKey, normalise } = await imp('src/game/audio/voiceKey.ts')

const args = process.argv.slice(2)
const flag = (name) => args.includes(`--${name}`)
const opt = (name) => args.find((a) => a.startsWith(`--${name}=`))?.split('=')[1]
const SCENES = ['01', '02', '03', '04']
const RUNS = Number(opt('runs') ?? 1500)
const VOICES = resolve(ROOT, 'art-source/voices')
const TAKES = resolve(VOICES, 'takes')
const INBOX = resolve(VOICES, 'inbox')
const OUT = resolve(ROOT, 'public/assets/audio/voice')
const CAST = JSON.parse(readFileSync(resolve(ROOT, 'src/story/voices.cast.json'), 'utf8'))
const TAKE_EXT = ['.webm', '.wav', '.m4a', '.mp3', '.ogg', '.aac', '.flac']

// ── Kokoro (tools/kokoro, its own install: cd tools/kokoro && npm install) ──

const KOKORO = resolve(ROOT, 'tools/kokoro')
async function kokoro() {
  const need = resolve(KOKORO, 'node_modules/kokoro-js')
  if (!existsSync(need)) {
    console.log('Kokoro is not installed: cd tools/kokoro && npm install')
    process.exit(1)
  }
  const { env } = await import(pathToFileURL(resolve(KOKORO, 'node_modules/@huggingface/transformers/dist/transformers.node.mjs')).href)
  const { KokoroTTS } = await import(pathToFileURL(resolve(need, 'dist/kokoro.js')).href)
  // the model (about 90 MB) downloads once, into tools/kokoro/.cache
  env.cacheDir = resolve(KOKORO, '.cache')
  const tts = await KokoroTTS.from_pretrained('onnx-community/Kokoro-82M-v1.0-ONNX', { dtype: 'q8', device: 'cpu' })
  // blended voices (below) aren't in Kokoro's own list: accept them, and say which accent to read them in
  const check = tts._validate_voice.bind(tts)
  tts._validate_voice = (v) => (v.startsWith('mix_') ? v.split('_')[1] : check(v))
  return tts
}

/**
 * A character's Kokoro voice: one of Kokoro's (`voice`), or a blend of several
 * (`mix`: { am_fenrir: 0.7, am_onyx: 0.3 }), read with an American (`lang`
 * 'a', the default) or British ('b') accent. A blend is a weighted average of
 * the voices' style tables, written where Kokoro looks for voices.
 */
async function voiceOf(c) {
  if (c.voice) return c.voice
  const parts = Object.entries(c.mix)
  const name = `mix_${c.lang ?? 'a'}_${parts.map(([v, w]) => `${v}${Math.round(w * 100)}`).join('_')}`
  const file = resolve(KOKORO, 'node_modules/kokoro-js/voices', `${name}.bin`)
  if (!existsSync(file)) {
    const total = parts.reduce((n, [, w]) => n + w, 0)
    let out = null
    for (const [v, w] of parts) {
      const buf = readFileSync(resolve(KOKORO, 'node_modules/kokoro-js/voices', `${v}.bin`))
      const f = new Float32Array(buf.buffer, buf.byteOffset, buf.byteLength / 4)
      out ??= new Float32Array(f.length)
      for (let i = 0; i < f.length; i++) out[i] += (f[i] * w) / total
    }
    writeFileSync(file, Buffer.from(out.buffer))
  }
  return name
}

// ── 1. Collect ────────────────────────────────────────────────────────────

const scenes = SCENES.map((n) => {
  const st = JSON.parse(readFileSync(resolve(ROOT, `src/story/scene${n}.staging.json`), 'utf8'))
  return { ...st.scene, story: JSON.parse(compileInk(resolve(ROOT, `src/story/scene${n}.ink`)).json), staging: st.beats }
})

let seed = 0x70ce
const rand = () => {
  seed |= 0
  seed = (seed + 0x6d2b79f5) | 0
  let t = Math.imul(seed ^ (seed >>> 15), 1 | seed)
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const pickOf = (a) => a[Math.floor(rand() * a.length)]

/** key → { key, speaker, text, scene, beat, before: what was said just before (for the actor) } */
const lines = new Map()
const add = (speaker, text, scene, beat, before) => {
  if (!speaker || !text?.trim()) return
  const t = normalise(text)
  const key = voiceKey(speaker, t)
  if (!lines.has(key)) lines.set(key, { key, speaker, text: t, scene, beat, before: before ?? null })
}

for (let run = 0; run < RUNS; run++) {
  let state = { vars: { ...DEFAULT_VARS, cash: Math.floor(rand() * 4) * 1000, respect: Math.floor(rand() * 300) }, choices: {}, flags: { contact_sal: rand() < 0.5 } }
  for (const scene of scenes) {
    const rt = new StoryRuntime(scene)
    rt.setVars(state)
    let last = null
    for (let b = rt.next(), guard = 0; b && guard < 3000; b = rt.next(), guard++) {
      if (b.type === 'line' && !b.thought) {
        add(b.speaker, b.text, scene.id, b.id, last)
        last = { speaker: b.speaker, text: b.text }
      } else if (b.type === 'choice') {
        if (b.context?.speaker) {
          add(b.context.speaker, b.context.text, scene.id, b.id, last)
          last = { speaker: b.context.speaker, text: b.context.text }
        }
        // anything Rookie could say back, locked or not (a richer route unlocks it)
        for (const o of b.options) add('rookie', spokenLine(b, o), scene.id, b.id, last)
        const open = b.options.filter((o) => !o.locked)
        if (!open.length) break
        const o = pickOf(open)
        rt.choose(o.id)
        const said = spokenLine(b, o)
        if (said) last = { speaker: 'rookie', text: said }
      } else if (b.type === 'qte') rt.setFlag(b.result, pickOf([0, 0.25, 0.5, 0.75, 1]))
      else if (b.type === 'explore') {
        for (const h of b.hotspots) {
          for (const l of h.lines ?? []) add(l.speaker, l.text, scene.id, b.id, null)
          if (h.ends || rand() < 0.5) for (const [k, v] of Object.entries(h.sets ?? {})) rt.setFlag(k, v)
        }
      }
      if (b.type === 'complete') break
    }
    state = rt.getVars()
  }
}

const all = [...lines.values()].sort((a, b) => a.speaker.localeCompare(b.speaker) || a.scene.localeCompare(b.scene) || a.beat.localeCompare(b.beat))
const keys = new Set(all.map((l) => l.key))

// ── 2. File the inbox ─────────────────────────────────────────────────────

mkdirSync(TAKES, { recursive: true })
mkdirSync(INBOX, { recursive: true })
let filed = 0
for (const f of readdirSync(INBOX)) {
  const m = f.match(/^([a-z0-9]+)__([a-z0-9]+)\.[a-z0-9]+$/i)
  if (!m || !TAKE_EXT.includes(extname(f).toLowerCase())) {
    if (!f.startsWith('.')) console.log(`inbox: don't know what "${f}" is (expected <speaker>__<key>.<ext>)`)
    continue
  }
  const dir = resolve(TAKES, m[1])
  mkdirSync(dir, { recursive: true })
  // a newer take replaces the older one, whatever its format
  for (const ext of TAKE_EXT) rmSync(resolve(dir, m[2] + ext), { force: true })
  renameSync(resolve(INBOX, f), resolve(dir, m[2] + extname(f).toLowerCase()))
  filed++
}
if (filed) console.log(`filed ${filed} take(s) from the inbox`)

// ── 2b. Kokoro: a generated take for every line nobody has recorded ──────
// Generated takes are listed in generated.json, so --redo only ever replaces
// those, never a real recording (a recording filed from the inbox takes over).

const GENERATED = resolve(VOICES, 'generated.json')
const generated = new Set(existsSync(GENERATED) ? JSON.parse(readFileSync(GENERATED, 'utf8')) : [])
const hasTake = (l) => TAKE_EXT.some((ext) => existsSync(resolve(TAKES, l.speaker, l.key + ext)))
for (const l of all) if (generated.has(l.key) && !existsSync(resolve(TAKES, l.speaker, `${l.key}.wav`))) generated.delete(l.key)

const redo = opt('redo')?.split(',') ?? []
for (const l of all)
  if (generated.has(l.key) && (redo.includes(l.speaker) || redo.includes('all'))) {
    rmSync(resolve(TAKES, l.speaker, `${l.key}.wav`), { force: true })
    generated.delete(l.key)
  }

if (flag('generate') || flag('audition')) {
  const tts = await kokoro()
  const say = async (l, file) => {
    const c = CAST[l.speaker]?.kokoro
    if (!c) return false
    const audio = await tts.generate(l.text, { voice: await voiceOf(c), speed: c.speed ?? 1 })
    mkdirSync(dirname(file), { recursive: true })
    await audio.save(file)
    return true
  }
  if (flag('audition')) {
    // one line per character, the same for everyone who has it, to compare voices side by side
    const dir = resolve(VOICES, 'auditions')
    for (const sp of new Set(all.map((l) => l.speaker))) {
      const mine = all.filter((l) => l.speaker === sp).sort((a, b) => Math.abs(a.text.length - 70) - Math.abs(b.text.length - 70))
      if (mine[0] && (await say(mine[0], resolve(dir, `${CAST[sp]?.name ?? sp}.wav`)))) console.log(`audition: ${CAST[sp]?.name ?? sp} — "${mine[0].text}"`)
    }
    console.log(`auditions in art-source/voices/auditions/`)
    await tts.model.dispose()
  }
  const only = opt('only')?.split(',')
  const todo = flag('audition') ? [] : all.filter((l) => !hasTake(l) && CAST[l.speaker]?.kokoro && (!only || only.includes(l.speaker))).slice(0, Number(opt('limit') ?? Infinity))
  console.log(`voicing ${todo.length} line(s) with Kokoro…`)
  let n = 0
  for (const l of todo) {
    if (await say(l, resolve(TAKES, l.speaker, `${l.key}.wav`))) generated.add(l.key)
    if (++n % 25 === 0 || n === todo.length) {
      console.log(`  ${n}/${todo.length}`)
      writeFileSync(GENERATED, JSON.stringify([...generated].sort()))
    }
  }
  // onnxruntime aborts the process at exit if its session is still open
  await tts.model.dispose()
}
writeFileSync(GENERATED, JSON.stringify([...generated].sort()))

/** key → take path */
const takes = new Map()
for (const sp of readdirSync(TAKES)) {
  const dir = resolve(TAKES, sp)
  if (!statSync(dir).isDirectory()) continue
  for (const f of readdirSync(dir)) if (TAKE_EXT.includes(extname(f).toLowerCase())) takes.set(f.slice(0, -extname(f).length), resolve(dir, f))
}

if (args.includes('--prune')) {
  let moved = 0
  for (const [key, path] of takes) {
    if (keys.has(key)) continue
    const to = resolve(VOICES, 'unused', path.slice(TAKES.length + 1))
    mkdirSync(dirname(to), { recursive: true })
    renameSync(path, to)
    takes.delete(key)
    moved++
  }
  console.log(`moved ${moved} take(s) no current line uses to art-source/voices/unused/`)
}

// ── 3. Convert ────────────────────────────────────────────────────────────

// trim silence at both ends, level to −16 LUFS,
// mono: one chain for both outputs
const FILTER = [
  'silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.08',
  'areverse',
  'silenceremove=start_periods=1:start_threshold=-45dB:start_silence=0.15',
  'areverse',
  'loudnorm=I=-16:TP=-1.5:LRA=11',
].join(',')
let converted = 0
let failedConv = 0
for (const l of all) {
  const take = takes.get(l.key)
  if (!take) continue
  const dir = resolve(OUT, l.speaker)
  mkdirSync(dir, { recursive: true })
  const outs = [
    [resolve(dir, `${l.key}.webm`), ['-c:a', 'libopus', '-b:a', '40k']],
    [resolve(dir, `${l.key}.mp3`), ['-c:a', 'libmp3lame', '-b:a', '64k']],
  ]
  const fresh = outs.every(([o]) => existsSync(o) && statSync(o).mtimeMs >= statSync(take).mtimeMs)
  if (fresh) continue
  try {
    for (const [o, codec] of outs) execFileSync('ffmpeg', ['-y', '-v', 'error', '-i', take, '-af', FILTER, '-ac', '1', '-ar', '48000', ...codec, o])
    converted++
  } catch (e) {
    failedConv++
    console.log(`✗ couldn't convert ${take}: ${String(e.message).split('\n')[0]}`)
  }
}
if (converted) console.log(`converted ${converted} take(s) for the game`)

// game files for lines that no longer exist (reworded or cut) are removed
if (existsSync(OUT))
  for (const sp of readdirSync(OUT))
    for (const f of readdirSync(resolve(OUT, sp))) if (!keys.has(f.replace(/\.(webm|mp3)$/, ''))) rmSync(resolve(OUT, sp, f))

const recorded = (l) => existsSync(resolve(OUT, l.speaker, `${l.key}.webm`)) && existsSync(resolve(OUT, l.speaker, `${l.key}.mp3`))
const manifest = {}
for (const l of all) if (recorded(l)) manifest[l.key] = l.speaker
writeFileSync(resolve(ROOT, 'src/story/voices.json'), JSON.stringify(manifest) + '\n')

// ── Script sheets, for reviewing the lines or recording them for real ────────────────────────

mkdirSync(resolve(VOICES, 'scripts'), { recursive: true })
const speakers = [...new Set(all.map((l) => l.speaker))]
for (const sp of speakers) {
  const c = CAST[sp] ?? {}
  const mine = all.filter((l) => l.speaker === sp)
  const md = [
    `# ${c.name ?? sp} — Underworld, Chapter 1`,
    '',
    c.who ? `**Who**: ${c.who}` : '',
    c.direction ? `**Voice**: ${c.direction}` : '',
    '',
    `${mine.length} lines. Record each as its own file named exactly as shown (any of .wav, .m4a, .mp3, .webm), one take per file; leave a little silence either side. Put them in art-source/voices/inbox/ (or send them over).`,
    '',
    ...mine.flatMap((l, i) => [
      `### ${i + 1}. \`${sp}__${l.key}\`  ${recorded(l) ? '✓ recorded' : ''}`,
      l.before ? `> *${CAST[l.before.speaker]?.name ?? l.before.speaker}:* ${l.before.text}` : '',
      '',
      `**${l.text}**`,
      '',
    ]),
  ].filter((x, i, a) => x !== '' || a[i - 1] !== '')
  writeFileSync(resolve(VOICES, 'scripts', `${sp}.md`), md.join('\n'))
}

// ── Report ────────────────────────────────────────────────────────────────

const rows = {}
for (const sp of speakers) {
  const mine = all.filter((l) => l.speaker === sp)
  const done = mine.filter(recorded).length
  rows[CAST[sp]?.name ?? sp] = { lines: mine.length, recorded: done, 'to record': mine.length - done }
}
console.log(`${all.length} spoken lines in Scenes ${SCENES.join(', ')}`)
console.table(rows)
const uncast = speakers.filter((sp) => !CAST[sp])
if (uncast.length) console.log(`no character brief for: ${uncast.join(', ')} (src/story/voices.cast.json)`)
console.log(`${Object.keys(manifest).length} voiced line(s) in the game`)
// (no process.exit: onnxruntime aborts the process if it's torn down that way)
process.exitCode = failedConv ? 1 : 0
